// ============================================
// Lesson 1: 変数宣言（let, const, var）
// ============================================

// このファイルを実行するには、ターミナルで以下を入力:
// node phase1/01-variables.js

// --------------------------------------------
// 1. let - 再代入可能な変数
// --------------------------------------------
let name = "太郎";
console.log("名前:", name);

name = "花子";  // 再代入OK
console.log("名前を変更:", name);

// --------------------------------------------
// 2. const - 再代入不可の定数
// --------------------------------------------
const PI = 3.14159;
console.log("円周率:", PI);

// PI = 3.14;  // エラー！constは再代入できない
// ↑コメントを外すとエラーになります

const SITE_NAME = "My Website";
console.log("サイト名:", SITE_NAME);

// --------------------------------------------
// 3. var - 古い書き方（非推奨）
// --------------------------------------------
var oldStyle = "これは古い書き方";
console.log(oldStyle);
// varは使わない方がいい（スコープの問題があるため）

// --------------------------------------------
// 4. 使い分けのルール
// --------------------------------------------
// - 基本は const を使う
// - 値を変更する必要がある場合のみ let を使う
// - var は使わない

// 例: ショッピングカート
const TAX_RATE = 0.1;        // 税率は変わらない → const
let totalPrice = 0;          // 合計は変わる → let
let itemCount = 0;           // 個数も変わる → let

totalPrice = 1000;
itemCount = 3;

console.log("---");
console.log("税率:", TAX_RATE);
console.log("合計金額:", totalPrice);
console.log("商品数:", itemCount);

